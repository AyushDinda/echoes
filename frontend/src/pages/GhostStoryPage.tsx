import React, { useState, useEffect } from 'react';
import { useSearchParams, useNavigate } from 'react-router-dom';
import { BookOpen, Sparkles, Copy, Check, RefreshCw, ArrowLeft, Scroll } from 'lucide-react';
import { AtmospherePicker } from '../components/AtmospherePicker';
import { api } from '../services/api';
import { Story, Session, AtmosphereType, StoryLength, EndingStyle } from '../types';

export const GhostStoryPage: React.FC = () => {
  const [searchParams] = useSearchParams();
  const navigate = useNavigate();
  const querySessionId = searchParams.get('session');

  const [activeSession, setActiveSession] = useState<Session | null>(null);
  const [story, setStory] = useState<Story | null>(null);
  const [length, setLength] = useState<StoryLength>('medium');
  const [atmosphere, setAtmosphere] = useState<AtmosphereType>('creepy');
  const [inspirationType, setInspirationType] = useState<'session' | 'custom'>('session');
  const [customTheme, setCustomTheme] = useState('');
  const [endingStyle, setEndingStyle] = useState<EndingStyle>('ambiguous');
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  // Load active session
  useEffect(() => {
    const loadSession = async () => {
      const sessionId = querySessionId || localStorage.getItem('echoes_active_session_id');
      if (sessionId) {
        try {
          const s = await api.getSession(sessionId);
          setActiveSession(s);
          setAtmosphere(s.atmosphere);
          if (s.stories && s.stories.length > 0) {
            setStory(s.stories[0]);
          }
        } catch {
          // ignore session load error
        }
      }
    };
    loadSession();
  }, [querySessionId]);

  const handleGenerateStory = async () => {
    let targetSessionId = activeSession?.id;

    setGenerating(true);
    setError(null);

    try {
      if (!targetSessionId) {
        // Create an ad-hoc session if none exists
        const newSess = await api.createSession('Grimoire Narrative Session', atmosphere);
        setActiveSession(newSess);
        targetSessionId = newSess.id;
        localStorage.setItem('echoes_active_session_id', newSess.id);
      }

      const newStory = await api.generateStory(targetSessionId, {
        length,
        atmosphere,
        inspiration_type: inspirationType,
        custom_theme: inspirationType === 'custom' ? customTheme : undefined,
        ending_style: endingStyle
      });

      setStory(newStory);
    } catch (err: any) {
      setError(err.message || 'The narrative thread unraveled. Unable to generate story.');
    } finally {
      setGenerating(false);
    }
  };

  const handleCopyStory = () => {
    if (!story) return;
    const textToCopy = `${story.title.toUpperCase()}\n\n${story.narrative}\n\n— Generated by Echoes (Atmosphere: ${story.atmosphere}, Ending: ${story.ending_style})`;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="max-w-5xl mx-auto px-4 py-6 space-y-6">
      {/* Top Navigation */}
      <div className="flex items-center justify-between border-b border-ghost-panelBorder pb-4">
        <button
          onClick={() => navigate('/')}
          className="flex items-center space-x-1.5 text-xs text-ghost-muted hover:text-ghost-green transition-colors font-mono"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>Return to Terminal</span>
        </button>
        <div className="flex items-center space-x-2 text-xs text-ghost-muted">
          <BookOpen className="w-4 h-4 text-ghost-amber" />
          <span className="font-semibold text-ghost-amber">GHOST STORY CHRONICLE</span>
        </div>
      </div>

      {/* Main Grid: Controls & Generated Story */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Controls Column (5 cols) */}
        <div className="lg:col-span-5 bg-ghost-panel border border-ghost-panelBorder rounded-lg p-5 space-y-5 shadow-lg">
          <div>
            <h2 className="text-sm font-bold text-ghost-green tracking-wider uppercase mb-1 flex items-center gap-2">
              <Scroll className="w-4 h-4" />
              <span>Weave Narrative</span>
            </h2>
            <p className="text-xs text-ghost-muted">
              Synthesize terminal invocations into a coherent, atmospheric horror story.
            </p>
          </div>

          {/* Inspiration Source */}
          <div className="space-y-2">
            <label className="text-xs text-ghost-muted uppercase tracking-wider block">Inspiration Source</label>
            <div className="grid grid-cols-2 gap-2 text-xs">
              <button
                type="button"
                onClick={() => setInspirationType('session')}
                className={`p-2 rounded border text-left font-mono transition-all ${
                  inspirationType === 'session'
                    ? 'bg-ghost-panelBorder border-ghost-green text-ghost-green shadow-phosphor'
                    : 'bg-ghost-bg border-ghost-panelBorder text-ghost-muted hover:text-ghost-text'
                }`}
              >
                <div className="font-semibold">Current Session</div>
                <div className="text-[10px] opacity-75">
                  {activeSession?.entries.length || 0} commands recorded
                </div>
              </button>

              <button
                type="button"
                onClick={() => setInspirationType('custom')}
                className={`p-2 rounded border text-left font-mono transition-all ${
                  inspirationType === 'custom'
                    ? 'bg-ghost-panelBorder border-ghost-green text-ghost-green shadow-phosphor'
                    : 'bg-ghost-bg border-ghost-panelBorder text-ghost-muted hover:text-ghost-text'
                }`}
              >
                <div className="font-semibold">Custom Theme</div>
                <div className="text-[10px] opacity-75">Define your omen</div>
              </button>
            </div>

            {inspirationType === 'custom' ? (
              <textarea
                value={customTheme}
                onChange={(e) => setCustomTheme(e.target.value)}
                maxLength={500}
                placeholder="e.g. A corrupted graphics pipeline displaying ghosts in framebuffers..."
                className="w-full bg-ghost-bg border border-ghost-panelBorder focus:border-ghost-green rounded p-2.5 text-xs text-ghost-text placeholder:text-ghost-muted/70 font-mono resize-none h-20 focus:outline-none"
              />
            ) : (
              activeSession && activeSession.entries.length > 0 && (
                <div className="p-2.5 rounded bg-ghost-bg border border-ghost-panelBorder text-[11px] text-ghost-muted space-y-1">
                  <div className="text-ghost-text/80 font-semibold">Active Invocations to Weave:</div>
                  <div className="truncate">
                    {activeSession.entries.slice(-4).map((e) => e.command_text).join(' • ')}
                  </div>
                </div>
              )
            )}
          </div>

          {/* Atmosphere Picker */}
          <div className="space-y-2">
            <AtmospherePicker value={atmosphere} onChange={setAtmosphere} disabled={generating} />
          </div>

          {/* Story Length */}
          <div className="space-y-2">
            <label className="text-xs text-ghost-muted uppercase tracking-wider block">Narrative Length</label>
            <div className="grid grid-cols-3 gap-2 text-xs">
              {(['short', 'medium', 'long'] as StoryLength[]).map((len) => (
                <button
                  key={len}
                  type="button"
                  onClick={() => setLength(len)}
                  className={`py-1.5 px-2 rounded border text-center font-mono capitalize transition-all ${
                    length === len
                      ? 'bg-ghost-panelBorder border-ghost-amber text-ghost-amber shadow-amber-glow font-semibold'
                      : 'bg-ghost-bg border-ghost-panelBorder text-ghost-muted hover:text-ghost-text'
                  }`}
                >
                  {len}
                </button>
              ))}
            </div>
          </div>

          {/* Ending Style */}
          <div className="space-y-2">
            <label className="text-xs text-ghost-muted uppercase tracking-wider block">Ending Cadence</label>
            <div className="grid grid-cols-2 gap-2 text-xs">
              {(['ambiguous', 'bittersweet', 'twist', 'hopeful'] as EndingStyle[]).map((style) => (
                <button
                  key={style}
                  type="button"
                  onClick={() => setEndingStyle(style)}
                  className={`py-1.5 px-2 rounded border text-center font-mono capitalize transition-all ${
                    endingStyle === style
                      ? 'bg-ghost-panelBorder border-ghost-green text-ghost-green shadow-phosphor font-semibold'
                      : 'bg-ghost-bg border-ghost-panelBorder text-ghost-muted hover:text-ghost-text'
                  }`}
                >
                  {style}
                </button>
              ))}
            </div>
          </div>

          {/* Submit Action */}
          <button
            type="button"
            disabled={generating}
            onClick={handleGenerateStory}
            className="w-full flex items-center justify-center space-x-2 py-2.5 px-4 rounded bg-ghost-amberDim/30 hover:bg-ghost-amberDim/60 text-ghost-amber hover:text-white border border-ghost-amber/50 font-mono text-sm transition-all shadow-amber-glow disabled:opacity-50 disabled:cursor-not-allowed"
          >
            {generating ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin text-ghost-amber" />
                <span>Conjuring Fiction...</span>
              </>
            ) : (
              <>
                <Sparkles className="w-4 h-4 text-ghost-amber" />
                <span className="font-semibold">{story ? 'Conjure New Story' : 'Generate Ghost Story'}</span>
              </>
            )}
          </button>
        </div>

        {/* Narrative Display Column (7 cols) */}
        <div className="lg:col-span-7 flex flex-col">
          {error && (
            <div className="mb-4 p-4 rounded bg-ghost-crimsonDim/20 border border-ghost-crimson/50 text-xs text-ghost-crimson">
              <p className="font-bold">Transmission Interrupted</p>
              <p className="mt-1">{error}</p>
            </div>
          )}

          {generating ? (
            <div className="flex-1 min-h-[350px] bg-ghost-panel border border-ghost-panelBorder rounded-lg p-8 flex flex-col items-center justify-center space-y-4 text-center">
              <div className="w-12 h-12 rounded-full border border-ghost-amber/40 bg-ghost-amberDim/20 flex items-center justify-center">
                <RefreshCw className="w-6 h-6 text-ghost-amber animate-spin" />
              </div>
              <div className="space-y-1">
                <h3 className="text-sm font-bold text-ghost-amber">Synthesizing Digital Specters</h3>
                <p className="text-xs text-ghost-muted max-w-sm">
                  The local language model is weaving terminal commands and {atmosphere} dread into a coherent chronicle...
                </p>
              </div>
            </div>
          ) : story ? (
            <div className="flex-1 bg-ghost-panel border border-ghost-panelBorder rounded-lg p-6 sm:p-8 flex flex-col space-y-5 shadow-2xl relative">
              {/* Story Header */}
              <div className="flex items-start justify-between border-b border-ghost-panelBorder pb-4">
                <div>
                  <div className="flex items-center space-x-2 mb-1">
                    <span className="text-[10px] uppercase tracking-wider px-2 py-0.5 rounded bg-ghost-panelBorder text-ghost-green font-mono">
                      {story.atmosphere}
                    </span>
                    <span className="text-[10px] uppercase tracking-wider px-2 py-0.5 rounded bg-ghost-panelBorder text-ghost-amber font-mono">
                      {story.ending_style} ending
                    </span>
                    {story.is_mock && (
                      <span className="text-[10px] uppercase tracking-wider px-2 py-0.5 rounded bg-ghost-amberDim/30 border border-ghost-amber/30 text-ghost-amber font-mono">
                        MOCK AI
                      </span>
                    )}
                  </div>
                  <h1 className="text-xl sm:text-2xl font-bold text-ghost-greenGlow text-glow tracking-wide">
                    {story.title}
                  </h1>
                </div>

                <button
                  onClick={handleCopyStory}
                  title="Copy story text to clipboard"
                  className="p-2 rounded bg-ghost-bg hover:bg-ghost-panelBorder border border-ghost-panelBorder text-ghost-text hover:text-ghost-green text-xs transition-colors"
                >
                  {copied ? <Check className="w-4 h-4 text-ghost-green" /> : <Copy className="w-4 h-4" />}
                </button>
              </div>

              {/* Story Narrative Content */}
              <div className="flex-1 overflow-y-auto space-y-4 text-ghost-ghostWhite font-sans text-sm sm:text-base leading-relaxed tracking-wide">
                {story.narrative.split('\n\n').map((paragraph, idx) => (
                  <p key={idx} className="first-letter:text-2xl first-letter:font-bold first-letter:text-ghost-green">
                    {paragraph}
                  </p>
                ))}
              </div>

              {/* Footer Note */}
              <div className="border-t border-ghost-panelBorder pt-3 text-[11px] text-ghost-muted flex items-center justify-between">
                <span>Echoes Fiction Engine • Local Inference</span>
                <span>{new Date(story.created_at).toLocaleDateString()}</span>
              </div>
            </div>
          ) : (
            <div className="flex-1 min-h-[350px] bg-ghost-panel border border-dashed border-ghost-panelBorder rounded-lg p-8 flex flex-col items-center justify-center space-y-3 text-center">
              <BookOpen className="w-10 h-10 text-ghost-muted/50" />
              <div className="space-y-1">
                <h3 className="text-sm font-semibold text-ghost-text">No Story Conjured Yet</h3>
                <p className="text-xs text-ghost-muted max-w-sm">
                  Select your atmosphere, length, and inspiration options on the left, then click "Generate Ghost Story".
                </p>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
